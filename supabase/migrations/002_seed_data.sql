* Клиент озвучивает требование соединения с руководителем 3 раза подряд после применения техники амортизации.
* Сумма ущерба или спорной транзакции превышает 50 000 рублей.
* Клиент является представителем СМИ, блогером с аудиторией от 10 000 подписчиков или госорганом.
* Имеет место нестандартная ситуация, не описанная ни в одном регламенте базы знаний.

